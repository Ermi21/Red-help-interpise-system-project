"""
Safety layer specifically for LLM-generated SQL.

This sits on top of app.database.readonly_guard (which is the generic,
DB-agnostic statement validator) and adds LLM-specific concerns: stripping
markdown fences the model likes to wrap SQL in, and — best effort —
flagging references to tables that were not in the schema context we gave
the model (a strong signal of hallucination, not a security boundary by
itself).
"""
import re

from app.database.readonly_guard import validate_sql
from app.utils.exceptions import UnsafeSQLError
from app.utils.logger import get_logger

logger = get_logger(__name__)

_FENCE_RE = re.compile(r"```(?:sql)?\s*([\s\S]*?)```", re.IGNORECASE)


def extract_sql(llm_output: str) -> str:
    """Strip markdown code fences and surrounding commentary the LLM may
    have added despite instructions not to."""
    match = _FENCE_RE.search(llm_output)
    candidate = match.group(1) if match else llm_output
    return candidate.strip().strip(";").strip()


def validate_llm_sql(llm_output: str, known_tables: set[str] | None = None) -> str:
    """Extract, validate, and return safe SQL generated by the LLM.

    Raises UnsafeSQLError if the statement fails validation. Logs (but does
    not block on) references to tables outside `known_tables`, since that
    check is advisory rather than a security boundary — the authoritative
    security boundary is readonly_guard + the DB-level readonly connection.
    """
    sql = extract_sql(llm_output)
    if not sql:
        raise UnsafeSQLError("Model did not return a SQL statement.")

    validated = validate_sql(sql)

    if known_tables:
        referenced = set(re.findall(r"\b\w+\b", validated.lower()))
        known_tables_lower = {t.lower() for t in known_tables}
        unknown = {t for t in referenced if t not in known_tables_lower}
        # Only used for logging/telemetry — never raises, to avoid false
        # positives from aliases, quoting, or schema-qualified names.
        if len(unknown) == len(known_tables) and known_tables:
            logger.info("Generated SQL may reference tables outside known schema context")

    return validated
